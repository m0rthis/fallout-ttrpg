async function build(packName, docs) {
  if (docs.length === 0) {
    console.log(`packs: skipping ${packName} (no source data)`);
    return;
  }
  const staging = fs.mkdtempSync(path.join(os.tmpdir(), `fallout-pack-${packName}-`));
  for (const doc of docs) {
    fs.writeFileSync(path.join(staging, `${doc._id}.json`), JSON.stringify(doc, null, 2));
  }
  const dest = path.join(outDir, packName);
  fs.mkdirSync(dest, { recursive: true });
  await compilePack(staging, dest, { log: false });
  fs.rmSync(staging, { recursive: true, force: true });
  console.log(`packs: compiled ${packName} (${docs.length} documents)`);
}

